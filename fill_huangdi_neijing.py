def fill_huangdi_neijing_data():
    """补全黄帝内经数据"""
    print("正在补全黄帝内经素问数据...")

    file_path = DATA_DIR / "hdnj" / "chapters.json"
    if not file_path.exists():
        print("  ✗ 黄帝内经数据文件不存在")
        return False

    with open(file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    chapters = data.get("chapters", [])
    print(f"  当前章节数：{len(chapters)}")

    # 补充第 6-81 章的数据
    for i in range(len(chapters)):
        chapter_num = chapters[i].get("chapter", i + 1)

        # 补充原文
        if chapter_num in HUANGDI_NEIJING_ORIGINAL:
            orig = HUANGDI_NEIJING_ORIGINAL[chapter_num]
            if not orig.startswith("（第") and len(orig) > 50:
                chapters[i]["original"] = orig

        # 补充王冰注
        if chapter_num in WANGBING_NOTES:
            chapters[i]["wangbing_note"] = WANGBING_NOTES[chapter_num]

        # 补充现代汉语翻译
        if chapter_num in MODERN_TRANSLATIONS:
            chapters[i]["modern_chinese"] = MODERN_TRANSLATIONS[chapter_num]

        # 移除不适用的字段
        if "gua_ci" in chapters[i]:
            del chapters[i]["gua_ci"]
        if "yao_ci" in chapters[i]:
            del chapters[i]["yao_ci"]

    # 保存数据
    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"  ✓ 已补全 {len(chapters)} 章数据")
    return True


